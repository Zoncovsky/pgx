//! The configuration files pgx owns inside the data directory.
use crate::config::{Config, Durability};
use std::path::Path;

/// `postgresql.conf`: a place for the user's own settings, then pgx's.
pub fn render_postgresql_conf() -> String {
    "# postgresql.conf — managed by pgx.\n\
     #\n\
     # Put your own settings above the include line. pgx regenerates pgx.conf\n\
     # on every `pgx start` from ~/.pgx/config.json, and its settings win.\n\
     \n\
     include 'pgx.conf'\n"
        .to_string()
}

/// `pgx.conf`: the PGX profile (configs/pgx-ephemeral.conf) adapted for a
/// local development runtime, plus the per-install settings.
pub fn render_pgx_conf(cfg: &Config, sock_dir: &Path, block_clone: bool) -> String {
    let durability = match cfg.durability {
        Durability::Ephemeral => {
            "# durability = ephemeral: survives a server crash, not an OS crash or\n\
             # power loss (fsync is off). `pgx init --durability full` for PostgreSQL defaults.\n\
             fsync = off\n\
             synchronous_commit = off\n\
             full_page_writes = off\n"
        }
        Durability::Full => {
            "# durability = full: PostgreSQL's defaults.\n\
             fsync = on\n\
             synchronous_commit = on\n\
             full_page_writes = on\n"
        }
    };
    let copy_method = if block_clone { "clone" } else { "copy" };
    let copy_note = if block_clone {
        "# This filesystem clones blocks: a new database shares its template's blocks."
    } else {
        "# This filesystem does not clone blocks: a new database copies its template."
    };
    format!(
        "# pgx.conf — generated by pgx on every start; do not edit (edit postgresql.conf).\n\
         \n\
         # --- Network ---------------------------------------------------------------\n\
         listen_addresses = '{listen}'\n\
         port = {port}\n\
         unix_socket_directories = '{sock}'\n\
         max_connections = 120\n\
         \n\
         # --- PGX profile: fixed instance cost ----------------------------------------\n\
         max_parallel_workers = 0\n\
         max_parallel_workers_per_gather = 0\n\
         pgrust.runtime = off\n\
         shared_buffers = 16MB\n\
         wal_buffers = 64kB\n\
         \n\
         # --- Storage -------------------------------------------------------------------\n\
         {copy_note}\n\
         file_copy_method = {copy_method}\n\
         \n\
         # --- Autovacuum at density -----------------------------------------------------\n\
         pgrust.autovacuum_skip_idle_databases = on\n\
         autovacuum_naptime = 300\n\
         \n\
         # --- Replication / production-only ---------------------------------------------\n\
         wal_level = minimal\n\
         max_wal_senders = 0\n\
         max_replication_slots = 0\n\
         max_logical_replication_workers = 0\n\
         hot_standby = off\n\
         \n\
         # --- Durability ------------------------------------------------------------------\n\
         {durability}\
         \n\
         # --- Logging and locale ------------------------------------------------------------\n\
         timezone = 'UTC'\n\
         log_timezone = 'UTC'\n\
         log_line_prefix = '%m [%p] %q%u@%d '\n\
         log_min_messages = warning\n\
         log_checkpoints = off\n",
        listen = cfg.listen.join(", "),
        port = cfg.port,
        sock = sock_dir.display().to_string().replace('\'', "''"),
    )
}

/// `pg_hba.conf`: trust on the Unix socket, scram-sha-256 on loopback TCP, plus
/// a scram-sha-256 line for each non-loopback listen address (so a container
/// exposed with `-p` is reachable, still password-protected).
pub fn render_hba(listen: &[String]) -> String {
    let mut out = String::from(
        "# pg_hba.conf — written by pgx init.\n         # TYPE  DATABASE  USER  ADDRESS       METHOD\n         local   all       all                 trust\n         host    all       all   127.0.0.1/32  scram-sha-256\n         host    all       all   ::1/128       scram-sha-256\n",
    );
    for a in listen {
        match a.as_str() {
            "127.0.0.1" | "::1" | "localhost" => {}
            "0.0.0.0" | "*" => {
                out.push_str("host    all       all   0.0.0.0/0     scram-sha-256\n")
            }
            "::" => out.push_str("host    all       all   ::/0          scram-sha-256\n"),
            other => out.push_str(&format!(
                "host    all       all   {other}/32  scram-sha-256\n"
            )),
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn cfg(d: Durability) -> Config {
        Config {
            port: 5444,
            password: "p".into(),
            durability: d,
            listen: vec!["127.0.0.1".into(), "::1".into()],
            run_dir: None,
            created_at: "t".into(),
        }
    }

    #[test]
    fn pgx_conf_carries_port_listen_socket_and_profile() {
        let s = render_pgx_conf(&cfg(Durability::Ephemeral), Path::new("/tmp/it's"), true);
        assert!(s.contains("port = 5444"));
        assert!(s.contains("listen_addresses = '127.0.0.1, ::1'"));
        assert!(s.contains("unix_socket_directories = '/tmp/it''s'"));
        assert!(s.contains("file_copy_method = clone"));
        assert!(s.contains("fsync = off"));
        assert!(s.contains("max_connections = 120"));
        assert!(s.contains("wal_level = minimal"));
    }

    #[test]
    fn full_durability_and_copy_fallback() {
        let s = render_pgx_conf(&cfg(Durability::Full), Path::new("/run/pgx"), false);
        assert!(s.contains("fsync = on"));
        assert!(s.contains("synchronous_commit = on"));
        assert!(s.contains("full_page_writes = on"));
        assert!(s.contains("file_copy_method = copy"));
        assert!(!s.contains("fsync = off"));
    }

    #[test]
    fn hba_is_loopback_only_by_default() {
        let h = render_hba(&["127.0.0.1".into(), "::1".into()]);
        assert!(h.contains("local   all       all                 trust"));
        assert!(h.contains("127.0.0.1/32  scram-sha-256"));
        assert!(h.contains("::1/128       scram-sha-256"));
        assert!(!h.contains("0.0.0.0"));
    }

    #[test]
    fn hba_widens_for_non_loopback_listen() {
        let h = render_hba(&["0.0.0.0".into()]);
        assert!(h.contains("0.0.0.0/0     scram-sha-256"), "{h}");
        assert!(h.contains("127.0.0.1/32"), "loopback still allowed: {h}");
        assert!(
            !h.contains("trust\nhost    all       all   0.0.0.0/0     trust"),
            "never trust on a wide address"
        );
    }
}
